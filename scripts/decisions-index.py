#!/usr/bin/env python3
"""Generate the docs/DECISIONS/README.md index from the decision records. MAN-440.

Every record PR used to prepend a row to the README's table, so two such PRs both inserted a
line after the same separator and the second conflicted once the first merged. The table is now
generated: each row comes from the record's file name, YYYY-MM-DD-manNNN-slug.md (the date and
ticket; without a manNNN, the first MAN-NNN in the heading), and its one-line `# ` heading (the
title, less a leading `YYYY-MM-DD — `). The table sits between the BEGIN/END marker comments;
the hand-written text around them is left alone. A record PR adds only its file, and the
Decisions Index workflow (.github/workflows/decisions-index.yml) runs --write on main and opens
the refresh PR. See docs/DECISIONS/2026-10-27-man440-generated-decisions-index.md.

Modes:
  (default)  lag-tolerant check: every listed row is correct and in order; records not listed
             yet are named but pass (a record PR's own record is not listed until the refresh).
  --strict   the README is exactly what --write would produce.
  --write    regenerate the table in place.

Exit codes: 0 ok; 1 the index is wrong (or, under --strict, incomplete or stale);
2 a record or the README is malformed.

stdlib only. Run: python3 scripts/decisions-index.py [--write | --strict] [--dir DIR]
"""
import argparse
import datetime
import os
import re
import sys
from dataclasses import dataclass

NAME = re.compile(r"^([0-9]{4}-[0-9]{2}-[0-9]{2})-(?:man-?([0-9]+)-)?[a-z0-9][a-z0-9-]*\.md$")
DATE_PREFIX = re.compile(r"^[0-9]{4}-[0-9]{2}-[0-9]{2}\s*[—–-]\s*")
HEADING_TICKET = re.compile(r"\bMAN-([0-9]+)\b")
BEGIN = "<!-- BEGIN decisions-index: generated by scripts/decisions-index.py; do not edit by hand -->"
END = "<!-- END decisions-index -->"
HEADER = "| Date | Ticket | Title |"
SEPARATOR = "|---|---|---|"
ROW = re.compile(r"^\| ([^|]+) \| ([^|]+) \| \[(.*)\]\(([^()\s]+)\) \|$")
NO_TICKET = "—"
README = "README.md"
DEFAULT_DIR = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "docs", "DECISIONS"))
REGENERATE = ("docs/DECISIONS/README.md is generated: drop your edit to it "
              "(`git checkout origin/main -- docs/DECISIONS/README.md`) or regenerate it with "
              "`python3 scripts/decisions-index.py --write`")


class RecordError(ValueError):
    """A record or the README cannot be indexed; the message names the file."""


@dataclass(frozen=True)
class Record:
    date: str
    ticket: int | None
    filename: str
    title: str

    def ticket_cell(self) -> str:
        return NO_TICKET if self.ticket is None else f"MAN-{self.ticket}"

    def row(self) -> str:
        return f"| {self.date} | {self.ticket_cell()} | [{self.title}]({self.filename}) |"

    def sort_key(self):
        # D3: newest first, then ticketed before ticketless, then ticket number descending,
        # then file name ascending. Fully determined by the file names and headings.
        return (-int(self.date.replace("-", "")), self.ticket is None, -(self.ticket or 0), self.filename)


def _normalize(text: str) -> str:
    return text.replace("\r\n", "\n")


def parse_record(filename: str, text: str) -> Record:
    """The index row's data for one record: date and ticket from the name, title from line 1."""
    where = f"docs/DECISIONS/{filename}: "
    m = NAME.match(filename)
    if not m:
        raise RecordError(where + "name it YYYY-MM-DD-manNNN-slug.md (lowercase slug); "
                          "the index reads the date and ticket from the name")
    date = m.group(1)
    try:
        datetime.date.fromisoformat(date)
    except ValueError:
        raise RecordError(where + f"{date} is not a calendar date") from None
    lines = _normalize(text).split("\n")
    first = lines[0]
    if not first.startswith("# ") or not first[2:].strip():
        raise RecordError(where + "line 1 must be the record's `# ` title")
    if len(lines) > 1 and lines[1].strip():
        raise RecordError(where + "line 2 must be blank; a `# ` heading is one line and the "
                          "index title is that line")
    heading = first[2:].strip()
    if m.group(2) is not None:
        ticket = int(m.group(2))
    else:
        t = HEADING_TICKET.search(heading)
        ticket = int(t.group(1)) if t else None
    title = DATE_PREFIX.sub("", heading, count=1).strip() or heading
    # D4: a `|` would split the table cell; nothing else is escaped.
    title = title.replace("|", "\\|")
    return Record(date=date, ticket=ticket, filename=filename, title=title)


def load_records(directory: str) -> list[Record]:
    """Every *.md record directly in directory (README.md excluded), in index order."""
    records = []
    for name in sorted(os.listdir(directory)):
        if not name.endswith(".md") or name == README:
            continue
        path = os.path.join(directory, name)
        if not os.path.isfile(path):
            continue
        with open(path, encoding="utf-8") as f:
            records.append(parse_record(name, f.read()))
    records.sort(key=Record.sort_key)
    return records


def render_block(records: list[Record]) -> str:
    """The marked block: BEGIN, a blank line, the table, a blank line, END."""
    return "\n".join([BEGIN, "", HEADER, SEPARATOR, *(r.row() for r in records), "", END])


def _block_span(readme: str) -> tuple[int, int]:
    """(start, end) character offsets of the marked block, END line included."""
    text = _normalize(readme)
    lines = text.split("\n")
    begins = [i for i, line in enumerate(lines) if line == BEGIN]
    ends = [i for i, line in enumerate(lines) if line == END]
    if len(begins) != 1 or len(ends) != 1 or begins[0] > ends[0]:
        raise RecordError(f"docs/DECISIONS/{README}: expected one `{BEGIN}` line followed by one "
                          f"`{END}` line (found {len(begins)} and {len(ends)})")
    start = sum(len(line) + 1 for line in lines[:begins[0]])
    end = sum(len(line) + 1 for line in lines[:ends[0]]) + len(END)
    return start, end


def replace_block(readme: str, block: str) -> str:
    """readme with its marked block replaced by block; the text around it is byte-identical."""
    text = _normalize(readme)
    start, end = _block_span(text)
    return text[:start] + block + text[end:]


def listed_rows(readme: str) -> list[str]:
    """The table rows inside the marked block (structure checked)."""
    text = _normalize(readme)
    start, end = _block_span(text)
    inner = text[start:end].split("\n")[1:-1]
    while inner and not inner[0].strip():
        inner.pop(0)
    while inner and not inner[-1].strip():
        inner.pop()
    if inner[:2] != [HEADER, SEPARATOR]:
        raise RecordError(f"docs/DECISIONS/{README}: the block must start with `{HEADER}` and "
                          f"`{SEPARATOR}`")
    return inner[2:]


def check(readme: str, records: list[Record], *, strict: bool) -> tuple[list[str], list[str]]:
    """(problems, unlisted record files). D6: the default check passes an index that lags the
    records (unlisted files are returned, not problems) but fails a dangling, duplicated or
    out-of-order row, or one whose date or name-derived ticket disagrees with its file name.
    strict also compares heading-derived tickets and titles, and requires the README to equal
    --write's output."""
    by_name = {r.filename: r for r in records}
    order = {r.filename: i for i, r in enumerate(records)}
    problems, seen, last = [], set(), -1
    for line in listed_rows(readme):
        m = ROW.match(line)
        if not m:
            problems.append(f"not a `| date | ticket | [title](file) |` row: {line!r}")
            continue
        date, ticket, _title, target = (g.strip() for g in m.groups())
        record = by_name.get(target)
        if record is None:
            problems.append(f"row links {target}, which is not a record in docs/DECISIONS")
            continue
        if target in seen:
            problems.append(f"{target} is listed twice")
            continue
        seen.add(target)
        # A ticket read from the heading (no manNNN in the name) can change with a heading
        # edit, like a title, so only --strict compares it.
        name_ticket = NAME.match(target).group(2) is not None
        if date != record.date or (ticket != record.ticket_cell() and (name_ticket or strict)):
            problems.append(f"{target}: row says {date} | {ticket}, the record says "
                            f"{record.date} | {record.ticket_cell()}")
        if order[target] < last:
            problems.append(f"{target} is out of order: newest first, then ticket highest first")
        last = max(last, order[target])
    unlisted = [r.filename for r in records if r.filename not in seen]
    if strict:
        problems.extend(f"does not list {name}" for name in unlisted)
        if not problems and replace_block(readme, render_block(records)) != _normalize(readme):
            problems.append("a row's title differs from its record's heading")
    return problems, unlisted


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Generate or check the docs/DECISIONS/README.md index (MAN-440). "
                    "Default: lag-tolerant check (unlisted records pass, wrong rows fail). "
                    "--strict: the README equals what --write produces. --write: regenerate it.",
        epilog="Exit codes: 0 ok; 1 the index is wrong, or incomplete or stale under --strict; "
               "2 a record or the README is malformed.")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="regenerate the table in place")
    mode.add_argument("--strict", action="store_true", help="require the README to be exactly current")
    parser.add_argument("--dir", default=DEFAULT_DIR, help="the records directory (default: docs/DECISIONS)")
    args = parser.parse_args(argv)
    readme_path = os.path.join(args.dir, README)
    try:
        records = load_records(args.dir)
        with open(readme_path, encoding="utf-8") as f:
            readme = f.read()
        if args.write:
            new = replace_block(readme, render_block(records))
            with open(readme_path, "w", encoding="utf-8", newline="\n") as f:
                f.write(new)
            print(f"wrote docs/DECISIONS/{README}: {len(records)} rows")
            return 0
        problems, unlisted = check(readme, records, strict=args.strict)
    except (RecordError, OSError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 2
    if problems:
        for p in problems:
            print(f"error: docs/DECISIONS/{README} {p}", file=sys.stderr)
        print(f"error: {REGENERATE}", file=sys.stderr)
        return 1
    listed = len(records) - len(unlisted)
    msg = f"ok: docs/DECISIONS/{README} lists {listed} of {len(records)} records"
    if unlisted:
        msg += ("; not listed yet (the Decisions Index workflow adds them after merge): "
                + ", ".join(unlisted))
    print(msg)
    return 0


if __name__ == "__main__":
    sys.exit(main())
